#[tokio::test]
async fn it_finalize_cancellation_races_are_barrier_controlled() {
    use Point::*;
    for (point, expect_tombstone, expect_bytes_at_key) in [
        (Claimed, false, false),
        (IntentCommitted, true, false),
        (BeforePlace, true, false),
        (AfterPlace, true, true),
        (BeforeCommit, true, true),
    ] {
        let rig = Rig::new().await;
        let data = bytes(12_000);
        let gate = rig.hooks.gate_at(point);
        let pushed = rig.push("cancel.bin", &data).await;
        let item = pushed.planned.item.clone();
        gate.wait_until_entered().await;
        assert_eq!(
            cancel_upload(&rig, &pushed.upload).await,
            StatusCode::NO_CONTENT,
            "{point:?}"
        );
        assert_eq!(
            cancel_upload(&rig, &pushed.upload).await,
            StatusCode::NO_CONTENT,
            "{point:?}: a duplicate DELETE is idempotent"
        );
        gate.open();
        rig.settle().await;

        assert!(
            rig.file_rows().await.is_empty(),
            "{point:?}: no visible file"
        );
        assert_eq!(rig.used().await, 0, "{point:?}: nothing charged");
        assert_eq!(rig.item_row(&item).await.0, "canceled", "{point:?}");
        assert_eq!(
            rig.final_path(&item).await.exists(),
            expect_bytes_at_key,
            "{point:?}: the physical blob"
        );
        assert_eq!(
            rig.object_state(&item).await.map(|found| found.0),
            expect_tombstone.then(|| "tombstoned".to_owned()),
            "{point:?}"
        );
        assert_eq!(
            rig.queue_rows().await,
            i64::from(expect_tombstone),
            "{point:?}"
        );
        assert_eq!(
            rig.jobs_for_delete().await,
            i64::from(expect_tombstone),
            "{point:?}"
        );
        assert!(
            !rig.staging_exists(&pushed.upload),
            "{point:?}: staging removed"
        );
        let (state, reserved, committed, reason) =
            rig.stack.reservation(&pushed.planned.session).await;
        assert_eq!(
            (state.as_str(), reserved, committed, reason.as_deref()),
            ("released", 0, None, Some("canceled")),
            "{point:?}"
        );
        let outcome = rig
            .finalizer()
            .finalize(item.parse().unwrap(), None)
            .await
            .unwrap();
        assert_eq!(
            outcome,
            FinalizeOutcome::Superseded,
            "{point:?}: a finalize after cancel"
        );
        assert_eq!(
            rig.queue_rows().await,
            i64::from(expect_tombstone),
            "{point:?}"
        );
    }
}

