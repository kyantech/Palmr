#[tokio::test]
async fn it_finalize_concurrent_finalizers_commit_once() {
    let rig = Rig::new().await;
    let data = bytes(25_000);
    let hold = rig.hooks.gate_at(Point::BeforeCommit);
    let pushed = rig.push("race.bin", &data).await;
    hold.wait_until_entered().await;
    let item: crate::features::transfers::model::SessionItemId =
        pushed.planned.item.parse().unwrap();
    let second = rig.second_finalizer("second");
    let third = rig.second_finalizer("third");
    let waiting = tokio::spawn({
        let second = second.clone();
        async move { second.finalize(item, None).await }
    });
    let waiting_too = tokio::spawn({
        let third = third.clone();
        async move { third.finalize(item, None).await }
    });
    tokio::task::yield_now().await;
    assert!(
        rig.file_rows().await.is_empty(),
        "nothing is returned as completed early"
    );
    hold.open();
    rig.settle().await;
    let results = [
        waiting.await.unwrap().unwrap(),
        waiting_too.await.unwrap().unwrap(),
    ];
    let file_id = rig.file_rows().await[0].id.clone();
    for result in results {
        assert_eq!(
            result,
            FinalizeOutcome::Committed {
                file_id: file_id.clone(),
                created: false
            }
        );
    }
    assert_eq!(
        rig.staging
            .place_calls
            .load(std::sync::atomic::Ordering::SeqCst),
        1
    );
    assert_converged(&rig, &pushed.planned.item, &pushed.planned.session, &data).await;
    rig.assert_no_overlap();
}

#[tokio::test]
async fn it_finalize_racing_triggers_create_one_result() {
    let rig = Rig::manual().await;
    let data = bytes(6_000);
    let pushed = rig.push("many.bin", &data).await;
    let item: crate::features::transfers::model::SessionItemId =
        pushed.planned.item.parse().unwrap();
    let finalizers: Vec<_> = (0..4)
        .map(|n| rig.second_finalizer(&format!("racer-{n}")))
        .collect();
    let mut tasks = Vec::new();
    for finalizer in &finalizers {
        let finalizer = finalizer.clone();
        tasks.push(tokio::spawn(
            async move { finalizer.finalize(item, None).await },
        ));
    }
    let mut created = 0;
    for task in tasks {
        match task.await.unwrap().unwrap() {
            FinalizeOutcome::Committed { created: true, .. } => created += 1,
            FinalizeOutcome::Committed { created: false, .. } => {}
            other => panic!("{other:?}"),
        }
    }
    assert_eq!(created, 1, "exactly one logical finalization wins");
    assert_converged(&rig, &pushed.planned.item, &pushed.planned.session, &data).await;
}

