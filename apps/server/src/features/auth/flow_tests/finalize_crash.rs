#[tokio::test]
async fn it_finalize_a_repeated_creation_after_finalization_is_idempotent() {
    let rig = Rig::new().await;
    let data = bytes(2_500);
    let pushed = rig.push_and_settle("again.bin", &data).await;
    assert_eq!(
        rig.stack.session_row(&pushed.planned.session).await.0,
        "completed"
    );
    let measured = rig
        .staging
        .measure_calls
        .load(std::sync::atomic::Ordering::SeqCst);

    for _ in 0..2 {
        let repeated = rig
            .stack
            .tus_send(
                rig.stack
                    .create_req(&rig.alice, &pushed.planned, Some(2_500)),
            )
            .await;
        assert_eq!(repeated.status, StatusCode::CREATED, "{}", repeated.text());
        assert!(header(&repeated, "location").ends_with(&pushed.upload));
        assert_eq!(header(&repeated, "upload-offset"), "2500");
    }
    let mismatched = rig
        .stack
        .tus_send(
            rig.stack
                .create_req(&rig.alice, &pushed.planned, Some(2_501)),
        )
        .await;
    assert_eq!(mismatched.status, StatusCode::UNPROCESSABLE_ENTITY);
    rig.settle().await;
    assert!(
        !rig.staging_exists(&pushed.upload),
        "staging is not recreated"
    );
    assert_eq!(
        rig.staging
            .measure_calls
            .load(std::sync::atomic::Ordering::SeqCst),
        measured,
        "nothing is finalized twice"
    );
    assert_converged(&rig, &pushed.planned.item, &pushed.planned.session, &data).await;
}

async fn recovered(rig: &Rig, planned: &[&super::tus::Planned], sizes: &[i64]) {
    for (planned, size) in planned.iter().zip(sizes) {
        assert_eq!(
            rig.item_row(&planned.item).await.0,
            "completed",
            "{}",
            planned.name
        );
        assert_eq!(rig.stack.session_row(&planned.session).await.0, "completed");
        let (state, reserved, committed, _) = rig.stack.reservation(&planned.session).await;
        assert_eq!(
            (state.as_str(), reserved, committed),
            ("committed", 0, Some(*size))
        );
    }
    assert_eq!(rig.file_rows().await.len(), planned.len());
    assert_eq!(
        rig.stack.counts().await.objects,
        i64::try_from(planned.len()).unwrap()
    );
    assert_eq!(rig.used().await, sizes.iter().sum::<i64>());
    assert_eq!(
        rig.audit_uploads().await,
        i64::try_from(planned.len()).unwrap()
    );
}

