struct Durable {
    state: String,
    stage: String,
    files: usize,
    object: Option<String>,
    at_key: bool,
    staged: bool,
}

async fn durable(rig: &Rig, item: &str, upload: &str) -> Durable {
    let (state, stage, _, _) = rig.item_row(item).await;
    Durable {
        state,
        stage,
        files: rig.file_rows().await.len(),
        object: rig.object_state(item).await.map(|(state, _, _)| state),
        at_key: rig.final_path(item).await.exists(),
        staged: rig.staging_exists(upload),
    }
}

async fn assert_converged(rig: &Rig, item: &str, session: &str, data: &[u8]) {
    let rows = rig.file_rows().await;
    assert_eq!(rows.len(), 1, "exactly one visible file");
    assert_eq!(rows[0].size, i64::try_from(data.len()).unwrap());
    assert_eq!(rig.stack.counts().await.objects, 1, "exactly one object");
    assert_eq!(rig.object_state(item).await.unwrap().0, "active");
    assert_eq!(
        rig.used().await,
        i64::try_from(data.len()).unwrap(),
        "one increment"
    );
    assert_eq!(rig.audit_uploads().await, 1, "one audit event");
    assert_eq!(
        rig.item_row(item).await.0,
        "completed",
        "the item is completed"
    );
    let (state, reserved, committed, _) = rig.stack.reservation(session).await;
    assert_eq!(
        (state.as_str(), reserved, committed),
        ("committed", 0, Some(i64::try_from(data.len()).unwrap())),
        "one settlement"
    );
    assert_eq!(
        Rig::digest_of(&rig.final_path(item).await).unwrap(),
        (data.len() as u64, Rig::digest(data)),
        "the exact generated bytes"
    );
}

#[tokio::test]
async fn it_finalize_crash_at_every_point_recovers_exactly_once() {
    use Point::*;
    let table = [
        (Dispatched, "uploading", "none", 0, None, false, true),
        (Claimed, "finalizing", "none", 0, None, false, true),
        (StagingSynced, "finalizing", "none", 0, None, false, true),
        (Measured, "finalizing", "none", 0, None, false, true),
        (MimeResolved, "finalizing", "none", 0, None, false, true),
        (
            IntentCommitted,
            "finalizing",
            "placing",
            0,
            None,
            false,
            true,
        ),
        (BeforePlace, "finalizing", "placing", 0, None, false, true),
        (AfterPlace, "finalizing", "placing", 0, None, true, false),
        (BeforeCommit, "finalizing", "placing", 0, None, true, false),
        (
            AfterCommit,
            "completed",
            "committed",
            1,
            Some("active"),
            true,
            false,
        ),
        (
            BeforeCleanup,
            "completed",
            "committed",
            1,
            Some("active"),
            true,
            false,
        ),
    ];
    assert_eq!(table.len(), Point::ALL.len());
    for (point, state, stage, files, object, at_key, staged) in table {
        let rig = Rig::new().await;
        let data = bytes(20_000);
        rig.hooks.crash_at(point);
        let pushed = rig.push("crash.bin", &data).await;
        rig.settle().await;
        let item = &pushed.planned.item;
        let found = durable(&rig, item, &pushed.upload).await;
        assert_eq!(rig.hooks.hits().last(), Some(&point), "{point:?}");
        assert_eq!(
            (
                found.state.as_str(),
                found.stage.as_str(),
                found.files,
                found.object.as_deref(),
                found.at_key,
                found.staged
            ),
            (state, stage, files, object, at_key, staged),
            "durable state after a crash at {point:?}"
        );
        if files == 0 {
            assert_eq!(rig.used().await, 0, "{point:?}: nothing is charged yet");
        }

        rig.restart().await;
        assert_converged(&rig, item, &pushed.planned.session, &data).await;
        let touched = rig
            .staging
            .measure_calls
            .load(std::sync::atomic::Ordering::SeqCst);
        rig.restart().await;
        assert_converged(&rig, item, &pushed.planned.session, &data).await;
        assert_eq!(
            rig.staging
                .measure_calls
                .load(std::sync::atomic::Ordering::SeqCst),
            touched,
            "{point:?}: a completed upload is not re-driven"
        );
        rig.assert_no_overlap();
    }
}

#[tokio::test]
async fn it_finalize_redrive_commits_placed_object_once() {
    let rig = Rig::new().await;
    let data = bytes(33_333);
    rig.hooks.crash_at(Point::AfterPlace);
    let pushed = rig.push("placed.bin", &data).await;
    rig.settle().await;
    let item = pushed.planned.item.clone();
    let (id_before, key_before): (String, String) = sqlx::query_as(
        "SELECT final_object_id, final_object_key FROM transfer_session_files WHERE id = ?1",
    )
    .bind(&item)
    .fetch_one(rig.stack.pools.reader().executor())
    .await
    .unwrap();
    assert!(rig.object_state(&item).await.is_none());
    assert!(rig.file_rows().await.is_empty());

    rig.restart().await;
    let (id_after, key_after): (String, String) = sqlx::query_as(
        "SELECT final_object_id, final_object_key FROM transfer_session_files WHERE id = ?1",
    )
    .bind(&item)
    .fetch_one(rig.stack.pools.reader().executor())
    .await
    .unwrap();
    assert_eq!(
        (id_before, key_before),
        (id_after, key_after),
        "no fresh identity"
    );
    assert_converged(&rig, &item, &pushed.planned.session, &data).await;
    let file_id = rig.file_rows().await[0].id.clone();

    for _ in 0..2 {
        rig.restart().await;
    }
    assert_converged(&rig, &item, &pushed.planned.session, &data).await;
    assert_eq!(
        rig.file_rows().await[0].id,
        file_id,
        "the same file identity"
    );
}

