#[test]
fn unit_gen_stream_capacity_boundary() -> Result<()> {
    ensure!(MAX_STREAM_SIZE == (1u64 << 38) - BLOCK_SIZE);
    GeneratedStream::new(&seed(1), MAX_STREAM_SIZE)?;
    for size in [MAX_STREAM_SIZE + 1, 1u64 << 38, 1u64 << 40, u64::MAX] {
        ensure!(
            matches!(
                GeneratedStream::new(&seed(1), size),
                Err(GenError::SizeExceedsCapacity { .. })
            ),
            "size {size}"
        );
    }

    let mut stream = GeneratedStream::new(&seed(1), MAX_STREAM_SIZE)?;
    stream.seek(MAX_STREAM_SIZE - 1)?;
    let mut buf = [0u8; 128];
    ensure!(stream.read(&mut buf)? == 1, "only the final byte remains");
    ensure!(stream.position() == MAX_STREAM_SIZE);
    ensure!(
        stream.read(&mut buf)? == 0,
        "nothing is generated beyond the cap"
    );
    ensure!(stream.seek(MAX_STREAM_SIZE + 1).is_err());
    Ok(())
}

#[test]
fn unit_gen_stream_tail_does_not_wrap_the_counter() -> Result<()> {
    let tail = generate_bytes(&seed(1), MAX_STREAM_SIZE, MAX_STREAM_SIZE - 128, 128)?;
    let head = generate_bytes(&seed(1), MAX_STREAM_SIZE, 0, 128)?;
    ensure!(
        tail != head,
        "counter wrap would replay the first keystream blocks"
    );
    Ok(())
}

#[test]
fn unit_gen_rejects_invalid_seeds_without_panicking() {
    let wide = "é".repeat(32);
    for bad in [
        "",
        "00",
        &"0".repeat(63),
        &"0".repeat(65),
        &"g".repeat(64),
        &format!("0x{}", "0".repeat(62)),
        &format!(" {}", "0".repeat(63)),
        wide.as_str(),
    ] {
        assert_eq!(Seed::from_hex(bad), Err(GenError::InvalidSeed), "{bad:?}");
        assert_eq!(
            Seed::from_canonical_hex(bad),
            Err(GenError::InvalidSeed),
            "{bad:?}"
        );
    }
    assert!(Seed::from_hex(&"A".repeat(64)).is_ok());
    assert_eq!(
        Seed::from_canonical_hex(&"A".repeat(64)),
        Err(GenError::InvalidSeed)
    );
}

